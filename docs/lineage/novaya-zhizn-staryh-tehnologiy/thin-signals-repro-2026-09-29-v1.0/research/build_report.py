"""Regenerate the report from the reviewed evidence records and deterministic scores."""
import json
from pathlib import Path
from score import rank, sensitivity
ROOT = Path(__file__).resolve().parent
def read(name):
    return json.loads((ROOT/name).read_text(encoding='utf-8-sig'))
sources=read('sources.json')
source_map={s['id']:s for s in sources}
cards=read('candidates.json')
card_map={c['id']:c for c in cards}
model=read('model.json')
results=rank(cards,model)
sens=sensitivity(cards,model)
def refs(ids):
    return '; '.join('[{}: {}]({})'.format(s,source_map[s]['title'],source_map[s]['url']) for s in dict.fromkeys(ids))
def cell(value):
    return str(value).replace('|',' / ').replace('\n',' ')
decisions={'priority_diligence':'Приоритет проверки','investigate':'Исследовать','watch':'Наблюдать','exclude':'Исключить'}
holds={'commercial_diligence':'Коммерческие компании/финансирование','rights_diligence':'Права и доступ к команде',
       'source_integrity_screen':'Полнота проверки исправлений/отзывов','historical_fit':'Точность исторической преемственности',
       'bottleneck_not_yet_removed':'Снятие старого барьера','incomplete_scores':'Неизвестные A/W',
       'system_comparison':'Сравнение полной системы','test_protocol':'Согласование решающего теста',
       'experimental_evidence':'Недостаточная экспериментальная опора'}
out=[(ROOT/'methodology.md').read_text(encoding='utf-8-sig')]
out+=['| № | ID | Технология | Исторический ориентир | Баллы L–U | Очередь |',
      '|---:|---|---|---:|---:|---|']
for r in results:
    c=card_map[r['id']]
    out.append('| {} | {} | {} | {} | {:g}–{:g} | {} |'.format(r['rank'],r['id'],c['name'],c['historical_year'],r['score_lower'],r['score_upper'],decisions[r['decision']]))
out+=['','**Матрица оценок.** Значения 0–5; «?» — неизвестно. B/E/N/T/D/M/A/W определены в разделе весов.','',
      '| ID | B | E | N | T | D | M | A | W |','|---|---:|---:|---:|---:|---:|---:|---:|---:|']
for r in results:
    c=card_map[r['id']]
    out.append('| '+c['id']+' | '+' | '.join('?' if c['scores'][k] is None else str(c['scores'][k]) for k in model['weights'])+' |')
out+=['','**Общие незакрытые условия.** Во всех 15 карточках остаются проверка коммерческого освоения и прав, полный скрининг исправлений/отзывов, сравнение полной системы и согласование теста. Первые три кандидата имеют приоритет сбора доказательств, а не разрешение на инвестицию. Предложенные тесты ещё не выполнены.','']
for r in results:
    c=card_map[r['id']]
    out+=['**{}. {} — {:g}–{:g}/100 ({})**'.format(r['rank'],c['name'],r['score_lower'],r['score_upper'],c['id']),'',
          '**История и прежний барьер.** '+c['history']+' '+c['barrier_then']+' '+refs(c['history_sources'])+'.','',
          '**Что изменилось; что показано.** '+c['change_now']+' '+c['evidence']+' '+refs(c['current_sources'])+'.','',
          '**Гипотеза первого продукта.** '+c['first_product']+' Возможные покупатели: '+c['buyers'],'',
          '**Главное возражение.** '+c['risk'],'',
          '**Решающий тест — предложение.** '+c['test']+' '+c['kill'],'',
          '**Рынок и доступ.** '+c['market_findings'],'',
          '**Оценка.** '+c['why_scores']+' Условный TRL: '+c['trl_estimate']+'. '+c['horizon'],'',
          '**Незакрытые ворота:** '+', '.join(holds.get(h,h) for h in r['holds'])+'.','']
    extra=[s for s in c['source_ids'] if s not in c['history_sources']+c['current_sources']]
    if extra:
        out+=['Дополнительные свидетельства: '+refs(extra)+'.','']
out+=['**11. Исключения и причины изменения списка**','',
      'Отрицательные результаты поиска сохранены. Коммерческий конкурент не доказывает, что вся физическая область закрыта патентом; он запрещает объявлять выбранное широкое направление свободным. Возврат возможен после обоснования действительно иной реализации и её доступности. Старое финансирование само по себе не доказывает сегодняшнюю занятость: нужны дата, состояние проекта и совпадение применения.','',
      '| Решение | Направление | Основание | Источник |','|---|---|---|---|']
for x in read('exclusions.json'):
    out.append('| {} | {} | {} | {} |'.format(x['decision'],cell(x['name']),cell(x['reason']),refs(x['source_ids'])))
out+=['','У пяти первоначальных карточек (T07, T08, T12, T14, T15) после отдельного поиска обнаружены существенные коммерческие противоречия. Они сохранены в retired_candidates.json и исключены из итоговых 15. Искусственные реснички также исключены после обнаружения поставляемого продукта Artic. Это произошло до финальной выдачи.','',
      '**12. Устойчивость и ограничения ранжирования**','',
      '| ID | Место в базовом расчёте | Лучшее–худшее при изменении одного веса |','|---|---:|---:|']
for r in results:
    rr=sens['rank_ranges'][r['id']]
    out.append('| {} | {} | {}–{} |'.format(r['id'],r['rank'],rr['best'],rr['worst']))
out+=['','Проверка охватывает 16 сценариев: ±20% по одному весу. Баллы экспертные; в данной выборке первые три позиции устойчивы только к этому виду возмущения. Новое сообщение о лицензии может исключить даже первого кандидата.','',
      '**13. Реестр источников**','',
      'Ниже перечислены использованные и отрицательные свидетельства. Указанная дата — дата публикации/события с доступной точностью; «не установлена» не означает старый источник. Все страницы проверялись в ходе исследования с датой среза 29.09.2026. `page_text` означает доступ к тексту страницы, `indexed_text_or_abstract` — аннотацию или индексированный фрагмент; это не обещание чтения полного PDF. Метаданные 43 DOI отдельно получены через Crossref.','']
for s in sources:
    verified=' DOI проверен через Crossref.' if s.get('metadata_verified') else ''
    out+=['- **{}**. [{}]({}); дата: {}; тип: {}; доступ: {}. {}{}'.format(s['id'],s['title'],s['url'],s.get('published') or 'не установлена',s['source_type'],s['access_level'],s['supports'],verified)]
out+=['','**14. Следующий этап: что должен вернуть продукт**','',
      'В штатном интерфейсе нужны отдельные очереди «кандидаты», «квалифицированные возможности», «наблюдение» и «исключено». В выдаче каждой строки показывать исторический тип, изменение барьера, одну измеренную метрику с условиями, ограничение результата, коммерческий статус, открытые ворота, дату проверки и следующий дешёвый тест. Если квалифицированных возможностей только две, интерфейс должен показать две и отдельно 13 исследовательских кандидатов.','',
      'Готовность текущей поставки: исследование и модель отбора реализованы, локальный расчёт работает. Коммерческая квалификация, лабораторная верификация, исторический бэктест модели и промышленная интеграция остаются следующими отдельными работами.','']
(ROOT/'REPORT.md').write_text('\n'.join(out),encoding='utf-8')
print('REPORT.md generated:',len(results),'cards;',len(sources),'sources')
